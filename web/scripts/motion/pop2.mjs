import { chromium, webkit } from "playwright-core";
import fs from "node:fs";
const [engine = "chromium"] = process.argv.slice(2);
const url = `http://127.0.0.1:${fs.readFileSync("/tmp/irperf/run/port", "utf8").trim()}/`;
const b = await (engine === "webkit" ? webkit : chromium).launch(engine === "chromium" ? { executablePath: "/home/iridium/.cache/ms-playwright/chromium-1254/chrome-linux64/chrome", args: ["--no-sandbox"] } : {});
const p = await b.newPage({ viewport: { width: 1200, height: 950 }, serviceWorkers: "block" });
p.on("pageerror", (e) => console.log("ERR", e.message.slice(0, 200)));
await p.goto(url + "?lang=zh#/s/e9631b25-0d51-4b49-8824-aecb67887ba7"); await p.waitForTimeout(4500);
const st = () => p.evaluate(() => { const e = document.querySelector("main [role=log]"); const d = document.querySelector("[role=dialog]"); const r = d?.getBoundingClientRect(); return { h: e.scrollHeight, top: Math.round(e.scrollTop), details: e.querySelectorAll("details").length, dialog: d ? [Math.round(r.width), Math.round(r.height)] : null, rowsIn: d?.querySelectorAll("button").length }; });
console.log("at rest", JSON.stringify(await st()));
const keys = p.locator('main [role=log] button[aria-haspopup=dialog][aria-expanded]');
const k = keys.last(); const y0 = (await k.boundingBox()).y;
await k.click(); await p.waitForTimeout(500);
console.log("opened", JSON.stringify(await st()), "row moved", Math.round((await k.boundingBox()).y - y0));
await p.screenshot({ path: `/tmp/irperf/pop-${engine}.png` });
await p.locator("[role=dialog] button").nth(1).click(); await p.waitForTimeout(400);
console.log("step", JSON.stringify(await st()), "dialogs", await p.locator("[role=dialog]").count());
await p.screenshot({ path: `/tmp/irperf/pop2-${engine}.png` });
await p.locator("[role=dialog] button").first().click(); await p.waitForTimeout(300);
console.log("back", JSON.stringify(await st()));
await p.keyboard.press("Escape"); await p.waitForTimeout(400);
console.log("closed", JSON.stringify(await st()), "row moved", Math.round((await k.boundingBox()).y - y0));
await b.close();
